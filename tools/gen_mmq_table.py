"""Generates src/ggml/mmq_table.cuh: ggml-cuda's MMQ with a per-expert pointer table (prefill).

  python tools/gen_mmq_table.py [llama.cpp dir]

Copies verbatim from ggml/src/ggml-cuda/mmq.cuh of the pinned llama.cpp the kernel mul_mat_q,
launch_mul_mat_q and mul_mat_q_switch_J, then applies checked textual substitutions (each must apply exactly
the expected number of times, otherwise the script fails):
  - mul_mat_q -> mul_mat_q_table, launch_mul_mat_q -> launch_mul_mat_q_table, mul_mat_q_switch_J -> ..._table_... ;
  - the parameter `const char * __restrict__ x` becomes `const char * const * __restrict__ table, uint32_t table_off`:
    the matrix of expert zt starts at table[zt] + table_off (gate, up or down in the [gate | up | down] slot
    of the expert cache, in VRAM or in mapped host memory) instead of x + zt * stride_channel_x;
  - in the three offset_x computations, the term fastdiv(zt, channel_ratio)*stride_channel_x is removed and x is
    read from the table.
Tile partitioning, stream-k, summation order and the fixup (mul_mat_q_stream_k_fixup, reused as is) are ggml's:
same bits as ggml's MMQ on a contiguous tensor (tests/mmq_parity.cu).
"""

import hashlib
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LLAMA = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("FNS_LLAMA_DIR", ROOT / "external/llama.cpp"))
SRC = LLAMA / "ggml/src/ggml-cuda/mmq.cuh"


def extract(text: str, start: str, end: str) -> str:
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


def sub(s: str, old: str, new: str, count: int) -> str:
    n = s.count(old)
    if n != count:
        raise SystemExit(f"expected {count} substitution(s), found {n}: {old!r}")
    return s.replace(old, new)


def main() -> None:
    text = SRC.read_text(encoding="utf-8")
    kernel = extract(text, "template <ggml_type type, int J, bool fallback, ggml_prec prec_src1>\n__launch_bounds__(ggml_cuda_mmq_get_nthreads(type, J, fallback, prec_src1), ggml_cuda_mmq_get_occupancy",
                     "template <ggml_type type, int J, bool fallback, ggml_prec prec_src1>\n__launch_bounds__(ggml_cuda_mmq_get_nthreads(type, J, fallback, prec_src1)/2, 1)")
    launch = extract(text, "template <ggml_type type, int J, bool fallback, ggml_prec prec_src1>\nstatic void launch_mul_mat_q(",
                     "template <ggml_type type, ggml_prec prec_src1>\nvoid mul_mat_q_case(")

    kernel = sub(kernel, "static __global__ void mul_mat_q(", "static __global__ void mul_mat_q_table(", 1)
    kernel = sub(kernel, "const char * __restrict__ x, const int * __restrict__ y,",
                 "const char * const * __restrict__ table, const uint32_t table_off, const int * __restrict__ y,", 1)
    kernel = sub(kernel,
                 "const int offset_x = fastdiv(wt, sample_ratio)*stride_sample_x + fastdiv(zt, channel_ratio)*stride_channel_x + it*I*stride_row_x;",
                 "const char * x = table[fastdiv(zt, channel_ratio)] + table_off;  // FNS: expert slot\n"
                 "        const int offset_x = fastdiv(wt, sample_ratio)*stride_sample_x + it*I*stride_row_x;", 3)

    launch = sub(launch, "static void launch_mul_mat_q(ggml_backend_cuda_context & ctx, const mmq_args & args, cudaStream_t stream) {",
                 "static void launch_mul_mat_q_table(ggml_backend_cuda_context & ctx, const char * const * table, uint32_t table_off, const mmq_args & args, cudaStream_t stream) {", 1)
    launch = sub(launch, "CUDA_SET_SHARED_MEMORY_LIMIT((mul_mat_q<type, J, false, prec_src1>), nbytes_shared);",
                 "CUDA_SET_SHARED_MEMORY_LIMIT((mul_mat_q_table<type, J, false, prec_src1>), nbytes_shared);", 1)
    launch = sub(launch, "CUDA_SET_SHARED_MEMORY_LIMIT((mul_mat_q<type, J,  true, prec_src1>), nbytes_shared);",
                 "CUDA_SET_SHARED_MEMORY_LIMIT((mul_mat_q_table<type, J,  true, prec_src1>), nbytes_shared);", 1)
    launch = sub(launch, "mul_mat_q<type, J, fallback, prec_src1><<<", "mul_mat_q_table<type, J, fallback, prec_src1><<<", 2)
    launch = sub(launch, "(args.x, args.y,", "(table, table_off, args.y,", 2)
    launch = sub(launch, "void mul_mat_q_switch_J(ggml_backend_cuda_context & ctx, const mmq_args & args, cudaStream_t stream) {",
                 "void mul_mat_q_table_switch_J(ggml_backend_cuda_context & ctx, const char * const * table, uint32_t table_off, const mmq_args & args, cudaStream_t stream) {", 1)
    launch = sub(launch, "fallback, prec_src1>(ctx, args, stream);", "fallback, prec_src1>(ctx, table, table_off, args, stream);", 16)
    launch = sub(launch, "launch_mul_mat_q<type,", "launch_mul_mat_q_table<type,", 16)

    commit = (LLAMA / ".git/HEAD").read_text().strip()
    head = f"""// src/ggml/mmq_table.cuh - GENERATED by tools/gen_mmq_table.py; do not edit by hand.
//
// ggml-cuda MMQ with a per-expert pointer table: transcription of ggml/src/ggml-cuda/mmq.cuh
// (mul_mat_q, launch_mul_mat_q, mul_mat_q_switch_J) from llama.cpp ({commit}); source sha256
// {hashlib.sha256(SRC.read_bytes()).hexdigest()}. Deviations from the original text are listed in the script.
//
// MIT License, Copyright (c) 2023-2026 The ggml authors. Permission is hereby granted, free of charge, to any person
// obtaining a copy of this software and associated documentation files (the "Software"), to deal in the Software
// without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute,
// sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so,
// subject to the following conditions: The above copyright notice and this permission notice shall be included in all
// copies or substantial portions of the Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND,
// EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE
// AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
// LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE
// SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.
#pragma once

#include "mmq.cuh"

"""
    out = ROOT / "src/ggml/mmq_table.cuh"
    out.write_text(head + kernel + launch, encoding="utf-8", newline="\n")
    print(out)


if __name__ == "__main__":
    main()
